create function public.submit_adoption(p_animal uuid,p_contact text,p_reason text) returns uuid
language plpgsql security definer set search_path=public as $$
declare a animals; result uuid;
begin
 if auth.uid() is null then raise exception 'Entre na sua conta para continuar.'; end if;
 select * into a from animals where id=p_animal for update;
 if not found or a.status<>'available' then raise exception 'Este animal não está disponível.'; end if;
 if exists(select 1 from adoption_requests where user_id=auth.uid() and animal_id=p_animal and status in ('pending','reviewing')) then raise exception 'Você já tem um pedido ativo para este animal.'; end if;
 insert into adoption_requests(user_id,animal_id,contact,reason) values(auth.uid(),p_animal,trim(p_contact),trim(p_reason)) returning id into result;
 insert into notifications(user_id,request_id,message) values(auth.uid(),result,'Seu pedido por '||a.name||' foi recebido.');
 return result;
end; $$;

create function public.transition_adoption(p_request uuid,p_status text) returns void
language plpgsql security definer set search_path=public as $$
declare r adoption_requests; a animals; other adoption_requests;
begin
 if auth.uid() is null then raise exception 'Entre na sua conta para continuar.'; end if;
 -- Todas as transições bloqueiam primeiro o animal e depois o pedido.
 -- Essa ordem serializa aprovações concorrentes e evita inversão de locks.
 select animal_id into r.animal_id from adoption_requests where id=p_request;
 if not found then raise exception 'Pedido não encontrado.'; end if;
 select * into a from animals where id=r.animal_id for update;
 select * into r from adoption_requests where id=p_request for update;
 if r.status not in ('pending','reviewing') then raise exception 'Este pedido já foi concluído.'; end if;
 if p_status='cancelled' then
   if r.user_id<>auth.uid() then raise exception 'Você só pode cancelar seus pedidos.'; end if;
 elsif not is_admin() then raise exception 'Acesso administrativo necessário.';
 elsif p_status not in ('reviewing','approved','rejected') or (p_status='reviewing' and r.status<>'pending') then raise exception 'Alteração não permitida.';
 end if;
 if p_status='approved' then
   if a.status<>'available' then raise exception 'Este animal não está disponível.'; end if;
   update animals set status='adopted' where id=a.id;
   for other in update adoption_requests set status='rejected',updated_at=now() where animal_id=a.id and id<>r.id and status in ('pending','reviewing') returning * loop
     insert into notifications(user_id,request_id,message) values(other.user_id,other.id,a.name||' encontrou outro lar. Seu pedido foi encerrado.');
   end loop;
 end if;
 update adoption_requests set status=p_status,updated_at=now() where id=r.id;
 insert into notifications(user_id,request_id,message) values(r.user_id,r.id,'Pedido por '||a.name||': '||case p_status when 'reviewing' then 'em análise' when 'approved' then 'aprovado' when 'rejected' then 'recusado' else 'cancelado' end||'.');
end; $$;

create function public.save_animal(p_id uuid,p_data jsonb,p_photos jsonb) returns uuid
language plpgsql security definer set search_path=public as $$
declare result uuid; prior text; photo jsonb; pos integer:=0; other adoption_requests;
begin
 if not is_admin() then raise exception 'Acesso administrativo necessário.'; end if;
 if jsonb_typeof(p_photos)<>'array' or jsonb_array_length(p_photos) not between 1 and 10 then raise exception 'Informe entre uma e dez fotos.'; end if;
 if p_id is not null then
   select status into prior from animals where id=p_id for update;
   if not found then raise exception 'Animal não encontrado.'; end if;
   if (p_data->>'status')='adopted' and prior<>'adopted' then raise exception 'A adoção deve ser concluída por um pedido.'; end if;
   if prior='adopted' and (p_data->>'status')<>'adopted' then raise exception 'Adoção concluída não pode ser reaberta.'; end if;
 else
   if (p_data->>'status') not in ('available','archived') then raise exception 'Status inválido.'; end if;
 end if;
 result:=coalesce(p_id,gen_random_uuid());
 insert into animals(id,name,species_id,breed_id,age_months,size,sex,description,city,state,status,responsible,vaccinated,neutered,demo)
 values(result,p_data->>'name',(p_data->>'species_id')::smallint,(p_data->>'breed_id')::smallint,(p_data->>'age_months')::integer,p_data->>'size',p_data->>'sex',p_data->>'description',p_data->>'city','SE',p_data->>'status',p_data->>'responsible',(p_data->>'vaccinated')::boolean,(p_data->>'neutered')::boolean,(p_data->>'demo')::boolean)
 on conflict(id) do update set name=excluded.name,species_id=excluded.species_id,breed_id=excluded.breed_id,age_months=excluded.age_months,size=excluded.size,sex=excluded.sex,description=excluded.description,city=excluded.city,status=excluded.status,responsible=excluded.responsible,vaccinated=excluded.vaccinated,neutered=excluded.neutered,demo=excluded.demo;
 delete from animal_photos where animal_id=result;
 for photo in select * from jsonb_array_elements(p_photos) loop
   insert into animal_photos(animal_id,url,position) values(result,photo#>>'{}',pos);pos:=pos+1;
 end loop;
 if (p_data->>'status')='archived' then
   for other in update adoption_requests set status='rejected',updated_at=now() where animal_id=result and status in ('pending','reviewing') returning * loop
     insert into notifications(user_id,request_id,message) values(other.user_id,other.id,'O anúncio de '||(p_data->>'name')||' foi retirado. Seu pedido foi encerrado.');
   end loop;
 end if;
 return result;
end; $$;
